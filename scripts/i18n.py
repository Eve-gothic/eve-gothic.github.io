def fmt_date(d, lang):
    if lang in CJK: return f'{d.year}年{d.month}月{d.day}日'
    m = MONTHS[lang][d.month - 1]
    if lang in ('pl', 'it'): return f'{d.day} {m} {d.year}'
    if lang == 'en': return f'{m} {d.day}, {d.year}'
    return f'{d.day} de {m} de {d.year}'

